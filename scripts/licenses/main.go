// Command licenses generates reproducible notices from the actual Go package graph.
// Run from anywhere in the repository: go run ./scripts/licenses [-check].
package main

import (
	"bytes"
	"crypto/sha256"
	"encoding/json"
	"flag"
	"fmt"
	"io"
	"io/fs"
	"os"
	"os/exec"
	"path/filepath"
	"runtime"
	"sort"
	"strings"
)

type module struct {
	Path, Version, Dir string
	Main               bool
	Replace            *module
}
type pkg struct {
	ImportPath, Dir string
	Standard        bool
	Module          *module
}
type usage struct {
	mod         module
	build, test bool
	targets     map[string]bool
}
type notice struct{ name, text string }

func main() {
	check := flag.Bool("check", false, "compare generated notices with THIRD_PARTY_NOTICES.md without writing")
	flag.Parse()
	if err := run(*check); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}
func command(root string, overrides []string, args ...string) ([]byte, error) {
	c := exec.Command("go", args...)
	c.Dir = root
	c.Env = os.Environ()
	for _, v := range overrides {
		key := strings.SplitN(v, "=", 2)[0] + "="
		filtered := c.Env[:0]
		for _, old := range c.Env {
			if !strings.HasPrefix(old, key) {
				filtered = append(filtered, old)
			}
		}
		c.Env = append(filtered, v)
	}
	var stderr bytes.Buffer
	c.Stderr = &stderr
	b, err := c.Output()
	if err != nil {
		return nil, fmt.Errorf("go %s: %w\n%s", strings.Join(args, " "), err, stderr.String())
	}
	return b, nil
}
func rootDir() (string, error) {
	d, err := os.Getwd()
	if err != nil {
		return "", err
	}
	for {
		if _, err := os.Stat(filepath.Join(d, "go.mod")); err == nil {
			return d, nil
		}
		parent := filepath.Dir(d)
		if parent == d {
			return "", fmt.Errorf("go.mod not found")
		}
		d = parent
	}
}
func run(check bool) error {
	root, err := rootDir()
	if err != nil {
		return err
	}
	uses := map[string]*usage{}
	stdDirs := map[string]bool{}
	inventory := func(target string, test bool, env []string, args ...string) error {
		data, err := command(root, env, args...)
		if err != nil {
			return err
		}
		dec := json.NewDecoder(bytes.NewReader(data))
		for {
			var p pkg
			if err := dec.Decode(&p); err == io.EOF {
				break
			} else if err != nil {
				return err
			}
			if p.Standard {
				stdDirs[p.Dir] = true
			}
			m := p.Module
			if m == nil || m.Main {
				continue
			}
			if m.Replace != nil {
				return fmt.Errorf("replacement module %s requires explicit provenance review", m.Path)
			}
			key := m.Path + "@" + m.Version
			u := uses[key]
			if u == nil {
				u = &usage{mod: *m, targets: map[string]bool{}}
				uses[key] = u
			}
			if test {
				u.test = true
			} else {
				u.build = true
			}
			u.targets[target] = true
		}
		return nil
	}
	if err := inventory("native tests", true, []string{"GOOS=" + runtime.GOOS, "GOARCH=" + runtime.GOARCH}, "list", "-deps", "-test", "-json", "./..."); err != nil {
		return err
	}
	for _, osname := range []string{"linux", "darwin", "windows"} {
		for _, arch := range []string{"amd64", "arm64"} {
			target := osname + "/" + arch
			if err := inventory(target, false, []string{"GOOS=" + osname, "GOARCH=" + arch, "CGO_ENABLED=0"}, "list", "-deps", "-json", "./cmd/looster"); err != nil {
				return err
			}
		}
	}
	var out bytes.Buffer
	out.WriteString("# Third-party notices\n\nGenerated by `go run ./scripts/licenses`. Do not edit by hand. Verify with `go run ./scripts/licenses -check`.\n\nInventory: union of native `go list -deps -test -json ./...` and `go list -deps -json ./cmd/looster` for linux, darwin, windows × amd64, arm64 with CGO_ENABLED=0. Build means used by a release target. Test-only means present only in the native test graph (which also includes native package builds and the generator). No claim is made about other build tags or CGO releases.\n\nAll matching license, copying, notice, authors and copyright files are reproduced recursively from used module directories, including bundled material and fixtures. Classifications are conservative content heuristics, not legal advice. Unrecognized license documents fail generation and require explicit review. Fully identified combined texts are marked for review. Supplemental attribution, patent and notice texts are labeled separately. The exact reviewed Lucent license is accepted only by its pinned SHA-256, not mislabeled as ISC. Source ZIP links provide the exact versioned module source, including MPL-covered source.\n\n")
	goroot := runtime.GOROOT()
	var env struct{ GOROOT, GOVERSION string }
	b, err := command(root, nil, "env", "-json", "GOROOT", "GOVERSION")
	if err != nil {
		return err
	}
	if err = json.Unmarshal(b, &env); err != nil {
		return err
	}
	goroot = env.GOROOT
	fmt.Fprintf(&out, "## Go toolchain %s\n\nSource: https://go.dev/dl/ (exact version %s). Toolchain LICENSE and PATENTS, plus notices beneath used standard-library package directories and toolchain third_party directories.\n\n", env.GOVERSION, env.GOVERSION)
	tool := map[string]notice{}
	for _, name := range []string{"LICENSE", "PATENTS"} {
		b, err := os.ReadFile(filepath.Join(goroot, name))
		if err != nil {
			return err
		}
		tool[name] = notice{name, string(b)}
	}
	for d := range stdDirs {
		if strings.HasPrefix(d, goroot+string(filepath.Separator)) {
			ns, err := collect(d)
			if err != nil {
				return err
			}
			for _, n := range ns {
				rel, _ := filepath.Rel(goroot, filepath.Join(d, n.name))
				n.name = filepath.ToSlash(rel)
				tool[n.name] = n
			}
		}
	}
	// Some runtime/compiler third-party notices are not in an importable package.
	for _, d := range []string{"src/third_party", "src/cmd/vendor", "src/vendor"} {
		ns, err := collect(filepath.Join(goroot, d))
		if err != nil && !os.IsNotExist(err) {
			return err
		}
		for _, n := range ns {
			n.name = d + "/" + n.name
			tool[n.name] = n
		}
	}
	keys := sortedKeys(tool)
	for _, k := range keys {
		if err := emit(&out, tool[k]); err != nil {
			return fmt.Errorf("Go toolchain: %w", err)
		}
	}
	for _, key := range sortedKeys(uses) {
		u := uses[key]
		ns, err := collect(u.mod.Dir)
		if err != nil {
			return err
		}
		if !hasModuleLicense(ns) {
			return fmt.Errorf("missing module license: %s", key)
		}
		kind := "test-only"
		if u.build {
			kind = "build"
		}
		fmt.Fprintf(&out, "## %s\n\nUsage: **%s**. Inventories: %s.\n\nSource ZIP: https://proxy.golang.org/%s/@v/%s.zip\n\n", key, kind, strings.Join(sortedKeys(u.targets), ", "), escape(u.mod.Path), escape(u.mod.Version))
		if u.mod.Path == "github.com/hashicorp/hcl" {
			fmt.Fprintf(&out, "MPL-2.0 source availability: this distribution uses github.com/hashicorp/hcl %s, whose covered source is available in the exact-version Source ZIP linked above. Download https://proxy.golang.org/%s/@v/%s.zip to obtain the covered source code corresponding to this dependency, including its MPL-2.0 license. The module source is distributed without local modifications by this project.\n\n", u.mod.Version, escape(u.mod.Path), escape(u.mod.Version))
		}
		for _, n := range ns {
			if err := emit(&out, n); err != nil {
				return fmt.Errorf("%s: %w", key, err)
			}
		}
	}
	b, err = os.ReadFile(filepath.Join(root, "web/static/vendor/D3-LICENSE.txt"))
	if err != nil {
		return err
	}
	out.WriteString("## D3 v7.9.0 (bundled JavaScript)\n\nUsage: **build**, embedded web asset. Source: https://github.com/d3/d3/tree/v7.9.0\n\n")
	if err := emit(&out, notice{"web/static/vendor/D3-LICENSE.txt", string(b)}); err != nil {
		return err
	}
	b, err = os.ReadFile(filepath.Join(root, "web/static/vendor/D3-THIRD-PARTY-LICENSES.txt"))
	if err != nil {
		return err
	}
	out.WriteString("### D3 transitive dependency notices\n\nThe following checked-in collection retains the pinned D3 runtime dependency inventory, package source locations and complete transitive license texts, including conservatively retained CLI-only dependencies.\n\n")
	if err := emit(&out, notice{"web/static/vendor/D3-THIRD-PARTY-LICENSES.txt", string(b)}); err != nil {
		return err
	}
	dest := filepath.Join(root, "THIRD_PARTY_NOTICES.md")
	return writeOrCheck(dest, out.Bytes(), check)
}

func writeOrCheck(dest string, generated []byte, check bool) error {
	if check {
		old, err := os.ReadFile(dest)
		if err != nil {
			return err
		}
		if !bytes.Equal(old, generated) {
			return fmt.Errorf("THIRD_PARTY_NOTICES.md is stale: run go run ./scripts/licenses")
		}
		return nil
	}
	return os.WriteFile(dest, generated, 0644)
}
func sortedKeys[V any](m map[string]V) []string {
	keys := make([]string, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	return keys
}
func escape(s string) string {
	var b strings.Builder
	for _, r := range s {
		if r >= 'A' && r <= 'Z' {
			b.WriteByte('!')
			b.WriteRune(r + 'a' - 'A')
		} else {
			b.WriteRune(r)
		}
	}
	return b.String()
}
func match(name string) bool {
	n := strings.ToLower(name)
	for _, prefix := range []string{"license", "licenses", "licence", "licences", "copying", "notice", "notices", "authors", "copyright", "patents"} {
		if n == prefix || strings.HasPrefix(n, prefix+".") || strings.HasPrefix(n, prefix+"-") || strings.HasPrefix(n, prefix+"_") {
			return true
		}
	}
	return false
}
func isLicense(name string) bool {
	n := strings.ToLower(filepath.Base(name))
	return strings.HasPrefix(n, "license") || strings.HasPrefix(n, "licence") || strings.HasPrefix(n, "copying")
}
func hasModuleLicense(ns []notice) bool {
	for _, n := range ns {
		if !strings.Contains(n.name, "/") && licenseDocument(n.name) && strings.TrimSpace(n.text) != "" {
			return true
		}
	}
	return false
}

func collect(dir string) ([]notice, error) {
	var ns []notice
	err := filepath.WalkDir(dir, func(path string, d fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if d.IsDir() {
			return nil
		}
		rel, err := filepath.Rel(dir, path)
		if err != nil {
			return err
		}
		selected := match(d.Name())
		for _, part := range strings.Split(filepath.ToSlash(filepath.Dir(rel)), "/") {
			if match(part) {
				selected = true
			}
		}
		if d.Type()&os.ModeSymlink != 0 {
			if selected {
				return fmt.Errorf("symlink notice requires review: %s", d.Name())
			}
			return nil
		}
		if !selected {
			return nil
		}
		b, err := os.ReadFile(path)
		if err != nil {
			return err
		}
		ns = append(ns, notice{filepath.ToSlash(rel), string(b)})
		return nil
	})
	sort.Slice(ns, func(i, j int) bool { return ns[i].name < ns[j].name })
	return ns, err
}
func classify(text string) string {
	s := strings.Join(strings.Fields(strings.ToLower(text)), " ")
	s = strings.NewReplacer("“", "\"", "”", "\"").Replace(s)
	var types []string
	if strings.Contains(s, "permission is hereby granted, free of charge") && (strings.Contains(s, "the software is provided \"as is\"") || strings.Contains(s, "the software is provided 'as is'")) {
		types = append(types, "MIT")
	}
	if strings.Contains(s, "apache license") && strings.Contains(s, "version 2.0") {
		types = append(types, "Apache-2.0")
	}
	if strings.Contains(s, "mozilla public license") && strings.Contains(s, "2.0") {
		types = append(types, "MPL-2.0")
	}
	if strings.Contains(s, "permission to use, copy, modify, and/or distribute this software for any purpose with or without fee") {
		types = append(types, "ISC")
	}
	if strings.Contains(s, "this is free and unencumbered software released into the public domain") && strings.Contains(s, "anyone is free to copy, modify, publish, use, compile, sell") && strings.Contains(s, "unlicense.org") {
		types = append(types, "Unlicense")
	}
	if strings.Contains(s, "redistribution and use in source and binary forms") && strings.Contains(s, "redistributions in binary form must reproduce") {
		if strings.Contains(s, "neither the name") || (strings.Count(s, "* ") == 3 && strings.Contains(s, "may not be used to endorse or promote products") && strings.Contains(s, "without specific prior written permission")) {
			types = append(types, "BSD-3-Clause")
		} else if (strings.Contains(s, "2.") && !strings.Contains(s, "3.")) || (strings.Count(s, "* redistributions") == 2 && strings.Count(s, "* ") == 2) {
			types = append(types, "BSD-2-Clause")
		} else {
			types = append(types, "BSD-style (review)")
		}
	}
	if len(types) == 1 {
		return types[0] + " (content match, review scope)"
	}
	if len(types) > 1 {
		return "Mixed text: " + strings.Join(types, ", ") + " (REVIEW)"
	}
	return "UNKNOWN / supplemental text (REVIEW)"
}

// This exact Lucent text is used by goja's ftoa implementation. It grants use,
// copying, modification and distribution with attribution, documentation and
// non-endorsement conditions. It is NOT ISC. Any byte change requires re-review.
const reviewedLucentSHA256 = "eb4df27f95a096a23d88e567331a4bee5590d22185942a1b0456197e29d03e59"

func licenseDocument(name string) bool {
	// Broad recursive discovery intentionally also retains source/CI files whose
	// names match, but those are not standalone license documents.
	switch strings.ToLower(filepath.Ext(name)) {
	case ".go", ".yml", ".yaml", ".json", ".js", ".ts":
		return false
	}
	if isLicense(name) || filepath.Base(name) == "D3-LICENSE.txt" || filepath.Base(name) == "D3-THIRD-PARTY-LICENSES.txt" {
		return true
	}
	for _, part := range strings.Split(filepath.ToSlash(filepath.Dir(name)), "/") {
		switch strings.ToLower(part) {
		case "license", "licenses", "licence", "licences", "copying":
			return true
		}
	}
	return false
}

func noticeClassification(n notice) (string, error) {
	if filepath.Base(n.name) == "D3-THIRD-PARTY-LICENSES.txt" {
		// Checking only the aggregate would let one recognized license mask an
		// unrecognized license elsewhere in the collection. Check each document.
		count := 0
		rest := n.text
		for {
			start := strings.Index(rest, "--- ")
			if start < 0 {
				break
			}
			rest = rest[start+4:]
			end := strings.Index(rest, " (verbatim from tarball) ---\n")
			if end < 0 {
				return "", fmt.Errorf("malformed D3 license document marker")
			}
			name := rest[:end]
			rest = rest[end+len(" (verbatim from tarball) ---\n"):]
			boundary := strings.Index(rest, "\n===================================================================")
			text := rest
			if boundary >= 0 {
				text = rest[:boundary]
			}
			if _, err := noticeClassification(notice{name, text}); err != nil {
				return "", fmt.Errorf("D3 embedded document %d: %w", count+1, err)
			}
			count++
			if boundary < 0 {
				break
			}
			rest = rest[boundary:]
		}
		if count == 0 {
			return "", fmt.Errorf("D3 collection contains no embedded license documents")
		}
	}
	if !licenseDocument(n.name) {
		base := strings.ToLower(filepath.Base(n.name))
		for _, prefix := range []string{"notice", "authors", "copyright", "patents"} {
			if base == prefix || strings.HasPrefix(base, prefix+".") || strings.HasPrefix(base, prefix+"-") || strings.HasPrefix(base, prefix+"_") {
				return "Supplemental attribution / notice / patent text (not a standalone license determination)", nil
			}
		}
		return "Supplemental matched source / metadata (not a license document)", nil
	}
	if fmt.Sprintf("%x", sha256.Sum256([]byte(n.text))) == reviewedLucentSHA256 {
		return "Reviewed Lucent permissive license (exact SHA-256: " + reviewedLucentSHA256 + ", not ISC)", nil
	}
	kind := classify(n.text)
	if strings.HasPrefix(kind, "UNKNOWN") || strings.HasPrefix(kind, "BSD-style") {
		return "", fmt.Errorf("unrecognized license document %s (SHA-256 %x): explicit license review required", n.name, sha256.Sum256([]byte(n.text)))
	}
	return kind, nil
}

func emit(out *bytes.Buffer, n notice) error {
	kind, err := noticeClassification(n)
	if err != nil {
		return err
	}
	fmt.Fprintf(out, "### `%s`\n\nClassification: %s\n\n", n.name, kind)
	fence := "```"
	for strings.Contains(n.text, fence) {
		fence += "`"
	}
	out.WriteString(fence + "text\n")
	out.WriteString(n.text)
	if !strings.HasSuffix(n.text, "\n") {
		out.WriteByte('\n')
	}
	out.WriteString(fence + "\n\n")
	return nil
}
